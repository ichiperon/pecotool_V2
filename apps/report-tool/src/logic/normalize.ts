/**
 * 経理数値の文字列を正規化する。
 *
 * 処理内容:
 * - 前後空白（全角空白含む）の trim
 * - 全角数字 → 半角数字（０〜９ → 0〜9）
 * - 全角マイナス・全角ハイフン → 半角マイナス（－ → -）
 * - 全角ピリオド → 半角ピリオド（．→ .）
 * - 全角パーセント → 半角パーセント（％ → %）
 * - 通貨記号の除去（¥ 円 \）
 *   ※ "$" は除去しない（外貨を壊さないため）
 * - 桁区切りカンマの除去（数値文脈のみ）
 * - 全角カンマ → 半角カンマに正規化後、桁区切り文脈のみ除去
 *   （数値文脈でない "1，2，3" は "1,2,3" を経由して化けさせない）
 * - △ / ▲ が先頭にある場合 → マイナス符号（△50 → -50、▲1,000 → -1000）
 *   ※ △▲ は財務書類で負数を表す慣習がある
 *
 * 数値に見えない文字列（「請求書」等）はそのまま返す（壊さない）。
 *
 * 仕様判断メモ:
 * - "%" はそのまま保持する（8% → 8%）。パーセント値を数値に変換すると
 *   後工程が混乱するため変換しない。
 * - "$" は除去しない（外貨対応のため）。
 * - 全角カンマ（，）は半角カンマへ正規化し、その後桁区切り文脈のみ除去する。
 *   数値文脈でない "1，2，3" → "1,2,3"（除去しない）。
 * - 小数点対応: "1,234.56" → "1234.56" / "１，２３４" → "1234"。
 * - パーセント終端対応: "1,234%" → "1234%"（桁区切りカンマの直後3桁の後ろに
 *   % が続く場合も桁区切りとして除去する）。
 * - 空文字はそのまま空文字で返す。
 * - 数値判定は厳格化済み（/^-?\d+(\.\d+)?%?$/）。
 *   "1.2.3" "5%5" "%" "-" 等は非数値として trim結果を返す（壊さない）。
 */
export function normalizeNumeric(s: string): string {
  if (s === "") return "";

  // 元の文字列の trim だけした版（非数値文脈で返す用）
  const trimmedOriginal = s.replace(/^[\s　]+|[\s　]+$/g, "");

  // 1. 前後空白 trim（全角空白含む）
  let v = trimmedOriginal;

  // 2. △/▲ が先頭にある場合のマイナス変換（除去してマイナスを前置する）
  //    先に処理しないと後続の変換で記号が残る
  let negative = false;
  if (/^[△▲]/.test(v)) {
    negative = true;
    v = v.slice(1).replace(/^[\s　]+/, "");
  }

  // 3. 全角数字 → 半角数字
  v = v.replace(/[０-９]/g, (c) =>
    String.fromCharCode(c.charCodeAt(0) - 0xff10 + 0x30)
  );

  // 4. 全角マイナス・全角ハイフン → 半角マイナス
  v = v.replace(/[－−]/g, "-");

  // 5. 全角ピリオド → 半角ピリオド
  v = v.replace(/[．]/g, ".");

  // 6. 全角パーセント → 半角パーセント
  v = v.replace(/％/g, "%");

  // 7. 通貨記号の除去（¥ 円 \）
  v = v.replace(/[¥\\]/g, "").replace(/円/g, "");

  // 8. 全角カンマ → 半角カンマに正規化（この時点ではまだ除去しない）
  //    "１，２３４" → "1,234" → 桁区切り除去 → "1234"
  //    "1，2，3"  → "1,2,3" → 桁区切りでないため除去せず → "1,2,3"
  v = v.replace(/，/g, ",");

  // 9. 桁区切りカンマの除去（数値文脈のみ）
  //    カンマの直後が3桁の数字グループであるものだけ除去する
  //    （3桁グループの後続が , . % のいずれか、または文字列末尾）
  //    "1,234%" のようにパーセント表記で終わるケースも桁区切りとして除去する
  v = v.replace(/,(?=\d{3}(?:[,.%]|$))/g, "");

  // 10. 数値に見えるか判定（厳格化）
  //     先頭符号任意・整数部必須・小数1個まで・末尾%1個まで
  //     "1.2.3" "5%5" "%" "-" 等は非数値として trimmedOriginal を返す（壊さない）
  //
  //     ※ negative=true の場合は v がすでに △▲ を除いた本体になっている。
  //       ここで isNumericLike を判定し、偽なら △▲ 付きの trimmedOriginal を返す。
  //       例: "△%" → v="%" → isNumericLike=false → trimmedOriginal="△%" を返す
  const isNumericLike = /^-?\d+(\.\d+)?%?$/.test(v);

  if (!isNumericLike) {
    // 数値に見えない → trim済みの元文字列を返す（壊さない）
    return trimmedOriginal;
  }

  // 11. マイナス符号の前置
  if (negative) {
    v = "-" + v;
  }

  return v;
}
